"""Backward-compatible facade over the canonical Pydantic tool registry."""

from __future__ import annotations

from typing import Any

from mcp_server.agent.schemas import ToolCall
from mcp_server.tools.registry import DEFAULT_TOOL_REGISTRY
from mcp_server.tools.specs import (
    IMAGE_TOOL_NAME,
    MAP_TOOL_NAME,
    USER_INTERACTION_TOOL_NAME,
    normalize_map_tool_arguments,
)


MAP_TOOL_OPS = DEFAULT_TOOL_REGISTRY.operations(MAP_TOOL_NAME)
IMAGE_TOOL_OPS = DEFAULT_TOOL_REGISTRY.operations(IMAGE_TOOL_NAME)
USER_INTERACTION_TOOL_OPS = DEFAULT_TOOL_REGISTRY.operations(USER_INTERACTION_TOOL_NAME)
TOOL_OPS_BY_NAME = {
    MAP_TOOL_NAME: MAP_TOOL_OPS,
    IMAGE_TOOL_NAME: IMAGE_TOOL_OPS,
    USER_INTERACTION_TOOL_NAME: USER_INTERACTION_TOOL_OPS,
}


def get_tool_definitions() -> list[dict[str, Any]]:
    """Return strict student-visible schemas generated by one registry.

    Returns:
        OpenAI function definitions preserving existing meta-tool names.
    """

    return DEFAULT_TOOL_REGISTRY.openai_definitions()


def expected_ops_for_tool(tool: str) -> set[str]:
    """Return registered operations for a student-visible tool.

    Args:
        tool: Stable meta-tool name.

    Returns:
        Registered operation names.
    """

    return DEFAULT_TOOL_REGISTRY.operations(tool)


def validate_tool_call(call: ToolCall | dict[str, Any]) -> tuple[bool, list[str]]:
    """Validate one tool call through the canonical Pydantic registry.

    Args:
        call: Parsed legacy or JSON tool call.

    Returns:
        Tuple ``(valid, errors)``.
    """

    valid, errors, _ = DEFAULT_TOOL_REGISTRY.validate_call(call)
    return valid, errors
