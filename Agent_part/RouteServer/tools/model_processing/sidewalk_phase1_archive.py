#!/usr/bin/env python3
"""Archive validated Phase1 CoT data into a ms-swift-ready dataset.

This is the final offline stage after ``sidewalk_phase1_dataset.py`` and
``sidewalk_phase1_cot_teacher.py``.  It deliberately does two jobs together:

1. Validate that each CoT row is still consistent with the geometry sidecars.
2. Materialize an archive root whose manifest can be passed directly to
   ``swift sft --dataset``.

Rows that fail validation are written to ``manifests/{split}.errors.jsonl`` and
are not included in the training manifest.  The archive can either reference the
original FPV/BEV files or materialize them under ``media/`` by hardlink, copy, or
symlink.  Hardlinks are preferred for local same-disk archives because they make
the dataset self-contained without duplicating file data.
"""

