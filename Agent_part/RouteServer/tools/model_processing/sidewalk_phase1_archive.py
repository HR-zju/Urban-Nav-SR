def parse_review_trajectory(value: Any) -> list[tuple[float, float]]:
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except Exception:
            return []
    points: list[tuple[float, float]] = []
    if not isinstance(value, list):
        return points
    for item in value:
        if not isinstance(item, (list, tuple)) or len(item) < 2:
            continue
        try:
            x = min(max(float(item[0]), 0.0), 1.0)
            y = min(max(float(item[1]), 0.0), 1.0)
        except Exception:
            continue
        points.append((x, y))
    return points


def html_image_src(value: Any, *, output_root: Path, sample_path: Path) -> str:
    if not value:
        return ""
    path = resolve_manifest_like_path(value, output_root=output_root / "manifests")
    if path is None:
        return ""
    try:
        return html.escape(os.path.relpath(path.resolve(), sample_path.parent.resolve()))
    except Exception:
        return html.escape(str(value))


def resolve_manifest_like_path(value: Any, *, output_root: Path) -> Path | None:
    if not value:
        return None
    path = Path(str(value)).expanduser()
    if path.is_absolute():
        return path
    return (output_root / path).resolve()


