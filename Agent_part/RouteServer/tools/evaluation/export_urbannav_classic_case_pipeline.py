#!/usr/bin/env python3
"""Export auditable Plan-and-Execute stages for one UrbanNav paper case.

The exporter intentionally distinguishes fields persisted during inference from
presentation evidence reconstructed from the final prediction. Current replay
runs retain the normalized goal decomposition and only the final reranker
response in ``prediction.trace``. Earlier reranker prompts and responses are
not recoverable byte-for-byte, so they are labelled rather than presented as
raw model logs.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

def parse_args() -> argparse.Namespace:
    """Parse command-line arguments.

    Returns:
        Parsed CLI arguments.
    """

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case-json", type=Path, required=True, help="Classic-case case.json generated by the figure tool.")
    parser.add_argument("--output-dir", type=Path, required=True, help="Directory for pipeline_trace.json and pipeline_trace.md.")
    return parser.parse_args()


def _read_json(path: Path) -> dict[str, Any]:
    """Read one JSON object.

    Args:
        path: JSON file path.

    Returns:
        Parsed object.

    Raises:
        ValueError: If the root JSON value is not an object.
    """

    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object: {path}")
    return value


def _destination_summary(value: Any) -> dict[str, Any]:
    """Return compact POI fields suitable for a paper figure.

    Args:
        value: Destination mapping.

    Returns:
        Compact destination evidence.
    """

    item = dict(value) if isinstance(value, dict) else {}
    return {
        "id": item.get("provider_poi_id") or item.get("place_id"),
        "name": item.get("name"),
        "type": item.get("type"),
        "lat": item.get("lat"),
        "lng": item.get("lng"),
        "route_distance_m": item.get("route_distance_m"),
        "provider_rank": item.get("rank"),
    }


def _candidate_payloads(leg: dict[str, Any]) -> list[dict[str, Any]]:
    """Build reranker-compatible candidate payloads from a saved prediction leg.

    Args:
        leg: Saved prediction route leg.

    Returns:
        Candidate payloads in the persisted final order.
    """

    payloads: list[dict[str, Any]] = []
    for index, value in enumerate(leg.get("candidate_destinations") or []):
        if not isinstance(value, dict):
            continue
        payloads.append(
            {
                "id": value.get("provider_poi_id") or value.get("place_id") or f"candidate-{index}",
                "name": value.get("name"),
                "type": value.get("type"),
                "distance_m": value.get("route_distance_m"),
                "candidate_kind": value.get("type"),
                "is_concrete_destination": value.get("lat") is not None and value.get("lng") is not None,
            }
        )
    return payloads


def _goal_to_intent(goal: dict[str, Any]) -> dict[str, Any]:
    """Convert a persisted goal to the runner's search-input contract.

    Args:
        goal: Normalized goal decomposition item.

    Returns:
        Search intent fields consumed by frozen replay POI search.
    """

    return {
        "destination_type": goal.get("destination_type") or goal.get("goal_type") or "poi",
        "destination_kind": goal.get("destination_kind") or "generic_poi",
        "search_keywords": goal.get("search_keywords") or goal.get("request_text") or "poi",
        "mode": goal.get("mode") or "foot",
        "radius_m": int(goal.get("radius_m") or 2000),
        "optimize_for": goal.get("optimize_for") or "distance",
        "max_candidates": goal.get("max_candidates"),
        "hard_constraints": goal.get("hard_constraints") or {},
    }


def _goal_decomposition_prompt_contract(user_instruction: str) -> dict[str, Any]:
    """Return the model-facing decomposition contract used by RouteServer.

    The original few-shot messages are generated at inference time and are not
    persisted in a prediction trace. This contract captures the exact output
    schema and the case-specific user request, while the source reference
    preserves the full canonical template.

    Args:
        user_instruction: Original case instruction.

    Returns:
        Prompt-contract record.
    """

    return {
        "system_contract": (
            "You are a trip-goal decomposer for map recommendation. Return JSON only. "
            "Top-level keys: goals, global_mode, notes. Each ordered goal contains: "
            "goal_index, goal_type, request_text, destination_type, destination_kind, search_keywords, "
            "mode, radius_m, optimize_for, hard_constraints, rationale. Do not solve routing or return destinations."
        ),
        "user_message": f"request: {user_instruction}\\nReturn the JSON object now.",
        "source_template": "src/mcp_server/llm.py:GoalDecomposer.build_messages",
        "persistence": "template reconstructed from source; generated few-shot prompt messages were not logged in this run",
    }


def _reranker_prompt_contract(
    *,
    user_instruction: str,
    parsed_intent: dict[str, Any],
    candidates: list[dict[str, Any]],
) -> dict[str, Any]:
    """Return the reranker contract and case-specific candidate payload.

    Args:
        user_instruction: Per-leg request text.
        parsed_intent: Normalized search intent.
        candidates: Candidate payloads supplied for presentation.

    Returns:
        Prompt-contract record.
    """

    candidate_ids = [str(item["id"]) for item in candidates]
    return {
        "system_contract": (
            "You rank map destination candidates for an embodied navigation system. Return JSON only with exactly "
            "two keys: ranked_candidate_ids and summary. ranked_candidate_ids is a non-empty best-to-worst order; "
            "every id must be copied exactly from candidate_ids. Prefer candidates that truly satisfy semantic intent."
        ),
        "user_payload": {
            "user_instruction": user_instruction,
            "parsed_intent": parsed_intent,
            "candidate_ids": candidate_ids,
            "candidates": candidates,
            "instruction": "Rank all candidates. Return the JSON object now.",
        },
        "source_template": "src/mcp_server/llm.py:CandidateReranker.build_messages",
        "persistence": "candidate set reconstructed from persisted post-rerank output; original pre-rerank request order was not logged",
    }


def _observed_ranking(leg: dict[str, Any]) -> list[dict[str, Any]]:
    """Return the post-rerank candidate order persisted in the prediction.

    Args:
        leg: Saved prediction route leg.

    Returns:
        Ordered compact candidate records.
    """

    output: list[dict[str, Any]] = []
    for position, candidate in enumerate(leg.get("candidate_destinations") or [], start=1):
        summary = _destination_summary(candidate)
        summary["observed_final_position"] = position
        output.append(summary)
    return output


def export_pipeline(payload: dict[str, Any]) -> dict[str, Any]:
    """Export the three model-facing P&E stages for one saved prediction.

    Args:
        payload: Object containing ``case``, ``prediction``, and ``evaluation``.

    Returns:
        JSON-ready pipeline record with explicit provenance fields.
    """

    case = dict(payload.get("case") or {})
    prediction = dict(payload.get("prediction") or {})
    evaluation = dict(payload.get("evaluation") or {})
    trace = dict(prediction.get("trace") or {})
    decomposition = dict(trace.get("goal_decomposition") or {})
    goals = [item for item in decomposition.get("goals") or [] if isinstance(item, dict)]
    legs = [item for item in prediction.get("pred_route_legs") or [] if isinstance(item, dict)]
    if not goals:
        # Single-destination runs persist their normalized model output as
        # ``trace.intent``. Normalize it only for presentation, while keeping
        # its provenance explicit in the exported trace.
        intent = dict(trace.get("intent") or {})
        if intent:
            goal = {
                "goal_index": 0,
                "goal_type": intent.get("destination_type"),
                "destination_type": intent.get("destination_type"),
                "destination_kind": intent.get("destination_kind"),
                "search_keywords": intent.get("search_keywords"),
                "mode": intent.get("mode"),
                "radius_m": intent.get("radius_m"),
                "optimize_for": intent.get("optimize_for"),
                "max_candidates": intent.get("max_candidates"),
                "hard_constraints": intent.get("hard_constraints"),
            }
            decomposition = {
                "goals": [goal],
                "is_multi_goal": False,
                "source": "trace.intent_normalized_for_single_goal_presentation",
            }
            goals = [goal]
    if not legs and isinstance(prediction.get("chosen_destination"), dict):
        legs = [{
            "leg_index": 1,
            "goal": goals[0] if goals else {},
            "poi_cache_key": (trace.get("poi_search") or {}).get("cache_key"),
            "candidate_destinations": prediction.get("candidate_destinations") or [],
            "chosen_destination": prediction.get("chosen_destination"),
            "route": prediction.get("route_polyline") or [],
            "route_summary": prediction.get("route_summary") or {},
        }]
    final_reranker_response = trace.get("reranker")

    stages: list[dict[str, Any]] = [
        {
            "stage": "intent_goal_decomposition",
            "model_input": {
                "user_instruction": case.get("instruction"),
                "prompt_contract": _goal_decomposition_prompt_contract(str(case.get("instruction") or "")),
            },
            "model_output": decomposition,
            "provenance": "persisted_model_output_normalized_by_goal_decomposer",
        }
    ]

    for leg_index, leg in enumerate(legs, start=1):
        goal = dict(leg.get("goal") or (goals[leg_index - 1] if leg_index <= len(goals) else {}))
        candidates = _candidate_payloads(leg)
        parsed_intent = _goal_to_intent(goal)
        reranker_prompt = _reranker_prompt_contract(
            user_instruction=str(goal.get("request_text") or case.get("instruction") or ""),
            parsed_intent=parsed_intent,
            candidates=candidates,
        )
        is_last_leg = leg_index == len(legs)
        stages.append(
            {
                "stage": "candidate_reranking",
                "leg_index": leg_index,
                "replay_poi_search": {
                    "cache_key": leg.get("poi_cache_key"),
                    "goal": goal,
                    "query_contract": parsed_intent,
                    "source": "frozen_replay_cache",
                },
                "model_input": {
                    "prompt_contract": reranker_prompt,
                    "candidate_input_provenance": "reconstructed_from_persisted_post_rerank_candidate_set; original_pre_rerank order was not logged",
                },
                "model_output": final_reranker_response if is_last_leg else None,
                "model_output_provenance": (
                    "persisted_final_reranker_response" if is_last_leg else "not_persisted; runner overwrote trace.reranker at each leg"
                ),
                "observed_final_candidate_order": _observed_ranking(leg),
            }
        )
        stages.append(
            {
                "stage": "selected_destination",
                "leg_index": leg_index,
                "selection_rule": "runner selects the first routable candidate after reranking; this is an execution rule, not a separate LLM response",
                "selected_destination": _destination_summary(leg.get("chosen_destination")),
                "route_execution": {
                    "declared_origin": leg.get("origin"),
                    "route_summary": leg.get("route_summary"),
                    "route_point_count": len(leg.get("route") or []),
                },
            }
        )

    return {
        "case": {
            "id": case.get("id"),
            "category": case.get("category"),
            "subcategory": case.get("subcategory"),
            "city": case.get("city"),
            "instruction": case.get("instruction"),
            "origin": case.get("origin"),
        },
        "protocol": "controlled-replay Plan-and-Execute",
        "trace_limitations": [
            "Frozen POI search and route lookup are runner/replay operations, not model-generated tool calls.",
            "The saved trace contains normalized goal decomposition and only the final reranker response.",
            "Earlier reranker inputs and outputs are reconstructed or unavailable unless a per-leg request log was enabled during inference.",
        ],
        "stages": stages,
        "evaluation": evaluation,
    }


def _markdown(record: dict[str, Any]) -> str:
    """Render a concise paper-facing summary.

    Args:
        record: Exported pipeline record.

    Returns:
        Markdown representation.
    """

    case = record["case"]
    lines = [
        "# UrbanNav Plan-and-Execute Case Trace",
        "",
        f"- Case: `{case['id']}`",
        f"- Protocol: `{record['protocol']}`",
        f"- Instruction: {case['instruction']}",
        "",
        "## Figure stages",
        "",
        "1. **Intent / goal decomposition**: use the persisted normalized JSON in `pipeline_trace.json`.",
        "2. **Candidate reranking**: show each leg's frozen candidate set, observed final order, and the selected item. Only the final leg's raw normalized reranker response is retained by this run.",
        "3. **Selected destination**: show the first routable post-rerank candidate and the corresponding replay route summary.",
        "",
        "## Per-leg evidence",
        "",
    ]
    for stage in record["stages"]:
        if stage["stage"] != "selected_destination":
            continue
        selected = stage["selected_destination"]
        route = stage["route_execution"]["route_summary"] or {}
        lines.append(
            f"- Leg {stage['leg_index']}: `{selected.get('name')}` ({selected.get('type')}, "
            f"{route.get('distance_m')} m)."
        )
    lines.extend(["", "## Provenance", "", *[f"- {item}" for item in record["trace_limitations"]], ""])
    return "\n".join(lines)


def main() -> None:
    """Export pipeline artifacts for one classic case."""

    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    record = export_pipeline(_read_json(args.case_json))
    (args.output_dir / "pipeline_trace.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.output_dir / "pipeline_trace.md").write_text(_markdown(record), encoding="utf-8")
    print(json.dumps({"json": str(args.output_dir / "pipeline_trace.json"), "markdown": str(args.output_dir / "pipeline_trace.md")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
